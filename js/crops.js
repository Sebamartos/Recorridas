// Busca el cultivo a partir de un texto libre (ej: "Soja 1ra" -> soja).
export function cropKey(text) {
  if (!text) return '';
  if (CROPS[text]) return text;
  const norm = text.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase();
  return Object.keys(CROPS).find((k) => norm.includes(k)) || '';
}

export function cropName(key) {
  return CROPS[key] ? CROPS[key].name : '';
}
